'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const html=fs.readFileSync(path.join(__dirname,'../public/index.html'),'utf8');
const begin=html.indexOf('function isNew(r)');
const end=html.indexOf('function prepareSelects()',begin);
assert(begin>=0&&end>begin);
const sandbox={norm:x=>String(x??'').normalize('NFD').replace(/[\u0300-\u036f]/g,'').toLowerCase().trim()};
vm.createContext(sandbox);
vm.runInContext(html.slice(begin,end),sandbox);
const student=(status,bm=false)=>({status,registered:true,preapproved:bm,special:false,approved:false,paid:status==='Pagado',type:'Nuevo',relation:'Empleado',isActive:true});
const students=[...Array.from({length:90},(_,i)=>student('Pre-aprobado',i<53)),...Array.from({length:26},()=>student('Inscrito')),...Array.from({length:4},()=>student('Docs completados')),...Array.from({length:4},()=>student('Aprobado')),...Array.from({length:5},()=>student('Pagado'))];
const m=sandbox.metric(students);
assert.equal(m.registered,129);
assert.equal(m.pre,90,'Estado E debe dar 90');
assert.equal(m.preEducation,53,'Aprobación BM debe dar 53');
assert.equal(m.paid,5);
assert(html.includes("['Pre-aprobado',number(m.pre),percentage(m.pre,baseline.registered)]"));
assert(html.includes("['Pre aprobado educamás',number(m.preEducation),percentage(m.preEducation,baseline.registered)]"));
assert(html.includes('const eligible=selectSource().filter(x=>x.preapproved||x.special||x.approved||x.paid'));
console.log('V5.3.6: 129 inscritos, 90 Pre-aprobado (E), 53 Pre aprobado educamás (BM); simulador sin cambios.');
